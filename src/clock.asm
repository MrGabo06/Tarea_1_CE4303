; =============================================================================
; clock.asm - UEFI x86-64
;
; Obtains the current time using UEFI Runtime Services -> GetTime()
; and displays the time in HH:MM:SS format.
;
; The clock is updated once per second using Boot Services -> Stall().
; The cursor is repositioned before each update so the same line is reused.
;
; NASM:
;     nasm -f win64 clock.asm -o clock.obj
;
; Calling convention:
;     Microsoft x64
;
; Entry point:
;     RCX = EFI_SYSTEM_TABLE*
;
; Return:
;     RAX = EFI_STATUS
; =============================================================================

default rel

bits 64

%include "uefi.inc"

global clock_main


; =============================================================================
; DATA
; =============================================================================

section .data


; -----------------------------------------------------------------------------
; Pointer to EFI_SYSTEM_TABLE
; -----------------------------------------------------------------------------

SystemTable:
    dq 0


; -----------------------------------------------------------------------------
; EFI_TIME structure
;
; Offset:
;     0  = Year        UINT16
;     2  = Month       UINT8
;     3  = Day         UINT8
;     4  = Hour        UINT8
;     5  = Minute      UINT8
;     6  = Second      UINT8
; -----------------------------------------------------------------------------

Time:
    times 16 db 0


; -----------------------------------------------------------------------------
; Final string:
;
;     HH:MM:SS\0
;
; Each character is stored as UTF-16 for UEFI OutputString().
; -----------------------------------------------------------------------------

TimeString:
    dw '0', '0', ':', '0', '0', ':', '0', '0', 0


; =============================================================================
; CODE
; =============================================================================

section .text


; =============================================================================
; clock_main
;
; Input:
;     RCX = EFI_SYSTEM_TABLE*
;
; Return:
;     RAX = EFI_STATUS
; =============================================================================

clock_main:


; -----------------------------------------------------------------------------
; PROLOGUE
; -----------------------------------------------------------------------------

    push    rbp
    mov     rbp, rsp
    sub     rsp, 32


; -----------------------------------------------------------------------------
; Save EFI_SYSTEM_TABLE*
; -----------------------------------------------------------------------------

    mov     [SystemTable], rcx


; =============================================================================
; CLOCK LOOP
; =============================================================================

.loop:


; -----------------------------------------------------------------------------
; Get EFI_RUNTIME_SERVICES*
; -----------------------------------------------------------------------------

    mov     rcx, [SystemTable]
    mov     rax, [rcx + ST_RuntimeServices]


; -----------------------------------------------------------------------------
; GetTime()
;
; EFI_STATUS GetTime(
;     EFI_TIME *Time,
;     EFI_TIME_CAPABILITIES *Capabilities
; );
;
; RCX = &Time
; RDX = NULL
; -----------------------------------------------------------------------------

    lea     rcx, [Time]
    xor     rdx, rdx
    call    [rax + RT_GetTime]


; -----------------------------------------------------------------------------
; Check EFI_STATUS
;
; EFI_SUCCESS = 0
; -----------------------------------------------------------------------------

    test    rax, rax
    jnz     .return


; -----------------------------------------------------------------------------
; FORMAT HOURS
;
; EFI_TIME.Hour = 0-23
;
; Example:
;     19 / 10 = 1
;     19 % 10 = 9
; -----------------------------------------------------------------------------

    movzx   eax, byte [Time + TIME_Hour]
    xor     edx, edx
    mov     ecx, 10
    div     ecx

; EAX = tens
; EDX = units

    add     eax, '0'
    mov     [TimeString + 0], ax

    mov     eax, edx
    add     eax, '0'
    mov     [TimeString + 2], ax


; -----------------------------------------------------------------------------
; FORMAT MINUTES
; -----------------------------------------------------------------------------

    movzx   eax, byte [Time + TIME_Minute]
    xor     edx, edx
    mov     ecx, 10
    div     ecx

; EAX = tens
; EDX = units

    add     eax, '0'
    mov     [TimeString + 6], ax

    mov     eax, edx
    add     eax, '0'
    mov     [TimeString + 8], ax


; -----------------------------------------------------------------------------
; FORMAT SECONDS
; -----------------------------------------------------------------------------

    movzx   eax, byte [Time + TIME_Second]
    xor     edx, edx
    mov     ecx, 10
    div     ecx

; EAX = tens
; EDX = units

    add     eax, '0'
    mov     [TimeString + 12], ax

    mov     eax, edx
    add     eax, '0'
    mov     [TimeString + 14], ax


; =============================================================================
; POSITION CURSOR
; =============================================================================

; -----------------------------------------------------------------------------
; Get EFI_SIMPLE_TEXT_OUTPUT_PROTOCOL*
; -----------------------------------------------------------------------------

    mov     rcx, [SystemTable]
    mov     rcx, [rcx + ST_ConOut]


; -----------------------------------------------------------------------------
; Set cursor position
;
; SetCursorPosition(
;     ConOut,
;     Column,
;     Row
; );
;
; RCX = ConOut
; RDX = Column = 0
; R8  = Row    = 0
; -----------------------------------------------------------------------------

    xor     rdx, rdx
    xor     r8, r8

    call    [rcx + OUT_SetCursorPosition]


; =============================================================================
; PRINT TIME
; =============================================================================

; -----------------------------------------------------------------------------
; Print HH:MM:SS
; -----------------------------------------------------------------------------

    lea     rcx, [TimeString]
    call    print_string


; =============================================================================
; WAIT ONE SECOND
; =============================================================================

    mov     rcx, [SystemTable]
    mov     rcx, [rcx + ST_BootServices]

    mov     rax, [rcx + BS_Stall]

    mov     rcx, 1000000
    call    rax


; -----------------------------------------------------------------------------
; Repeat the clock loop
; -----------------------------------------------------------------------------

    jmp     .loop


; =============================================================================
; RETURN
; =============================================================================

.return:

    add     rsp, 32
    pop     rbp
    ret


print_string:


; -----------------------------------------------------------------------------
; PROLOGUE
; -----------------------------------------------------------------------------

    push    rbp
    mov     rbp, rsp
    sub     rsp, 32


; -----------------------------------------------------------------------------
; RDX = String
; -----------------------------------------------------------------------------

    mov     rdx, rcx


; -----------------------------------------------------------------------------
; RCX = EFI_SYSTEM_TABLE*
; -----------------------------------------------------------------------------

    mov     rcx, [SystemTable]


; -----------------------------------------------------------------------------
; RCX = ConOut
; -----------------------------------------------------------------------------

    mov     rcx, [rcx + ST_ConOut]


; -----------------------------------------------------------------------------
; OutputString(ConOut, String)
; -----------------------------------------------------------------------------

    call    [rcx + OUT_OutputString]


    add     rsp, 32
    pop     rbp
    ret